"""Resource generation tests for runtime-composition.md section 5."""

import hashlib
import json
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

REPOSITORY_ROOT = Path(__file__).parents[1]


@pytest.fixture
def repository(tmp_path: Path) -> Path:
    tools = tmp_path / "tools"
    tools.mkdir()
    for name in ("build_runtime_manifest.py", "sync_public_reference.py"):
        shutil.copy2(REPOSITORY_ROOT / "tools" / name, tools / name)
    resources = tmp_path / "src/vividly/resources"
    (resources / "runtime/vividly").mkdir(parents=True)
    (resources / "reference").mkdir()
    (resources / "runtime/vividly/version.txt").write_bytes(b"0.0.3\n")
    (resources / "runtime/index.html").write_bytes(b"<!doctype html>\n")
    (resources / "runtime/vividly-runtime.json").write_bytes(b'{"old":true}\r\n')
    (resources / "reference/example.md").write_bytes(b"# Reference\n")
    return tmp_path


def test_manifest_rejects_all_crlf_text_inputs_without_writing(repository: Path) -> None:
    resources = repository / "src/vividly/resources"
    invalid = [
        resources / f"runtime/vividly/example.{extension}"
        for extension in ("css", "html", "js", "json", "md", "svg", "txt")
    ]
    invalid.append(resources / "reference/example.md")
    for path in invalid:
        path.write_bytes(b"first\r\nsecond\r\n")
    manifest = resources / "runtime/vividly-runtime.json"
    before = manifest.read_bytes()

    result = subprocess.run(
        [sys.executable, str(repository / "tools/build_runtime_manifest.py")],
        capture_output=True,
        text=True,
        check=False,
    )

    assert result.returncode == 1
    assert "CRLF" in result.stderr
    assert "LF" in result.stderr
    for path in invalid:
        assert path.relative_to(repository).as_posix() in result.stderr
    assert "Traceback" not in result.stderr
    assert manifest.read_bytes() == before


def test_manifest_preserves_binary_bytes_and_writes_canonical_lf(repository: Path) -> None:
    resources = repository / "src/vividly/resources"
    binaries = (
        resources / "runtime/vividly/font.woff2",
        resources / "reference/icon.ico",
    )
    content = b"\x00\xff\r\nbinary\r\n"
    for path in binaries:
        path.write_bytes(content)

    command = [sys.executable, str(repository / "tools/build_runtime_manifest.py")]
    subprocess.run(command, check=True, capture_output=True)

    manifest = resources / "runtime/vividly-runtime.json"
    generated = manifest.read_bytes()
    document = json.loads(generated)
    assert generated == (
        json.dumps(document, ensure_ascii=False, separators=(",", ":"), sort_keys=True) + "\n"
    ).encode("utf-8")
    assert document["files"]["vividly/font.woff2"] == hashlib.sha256(content).hexdigest()
    assert document["reference_files"]["icon.ico"] == hashlib.sha256(content).hexdigest()
    assert "vividly-runtime.json" not in document["files"]
    for path in binaries:
        assert path.read_bytes() == content

    subprocess.run(command, check=True, capture_output=True)
    assert manifest.read_bytes() == generated


def test_reference_check_rejects_crlf_and_sync_restores_lf(repository: Path) -> None:
    destination = repository / "site/reference"
    destination.mkdir(parents=True)
    notice = (
        b"<!-- Generated by tools/sync_public_reference.py from "
        b"src/vividly/resources/reference; do not edit this copy. -->\n\n"
    )
    expected = notice + b"# Reference\n"
    output = destination / "example.md"
    output.write_bytes(expected.replace(b"\n", b"\r\n"))
    command = [sys.executable, str(repository / "tools/sync_public_reference.py")]

    result = subprocess.run([*command, "--check"], capture_output=True, text=True, check=False)

    assert result.returncode == 1
    assert "out of date" in result.stdout
    subprocess.run(command, check=True, capture_output=True)
    assert output.read_bytes() == expected
    subprocess.run([*command, "--check"], check=True, capture_output=True)
